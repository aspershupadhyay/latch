# Writes the package manifests for one release from its archives:
#
#   packaging/render.sh v0.1.0 dist https://github.com/aspershupadhyay/latch/releases/download/v0.1.0 out
#
#   out/Formula/latch.rb    Homebrew (macOS and Linux): brew install latch from our tap
#   out/bucket/latch.json   Scoop (Windows): scoop install latch from our bucket
#   out/winget/...          winget manifests, ready to submit to microsoft/winget-pkgs
#
# The release workflow runs it on every tag and proposes the first two for main,
# where the repository itself is the tap and the bucket (docs/install.md). CI runs
# it against a local web server to install the packages for real.
set -euo pipefail

tag="$1" dist="$2" base="$3" out="$4"
version="${tag#v}"
sum() {
  if command -v sha256sum >/dev/null; then sha256sum "$dist/$1"; else shasum -a 256 "$dist/$1"; fi | cut -d' ' -f1
}
for f in macos-arm64.tar.gz macos-x86_64.tar.gz linux-x86_64.tar.gz windows-x86_64.zip; do
  [ -f "$dist/latch-$tag-$f" ] || { echo "missing $dist/latch-$tag-$f" >&2; exit 1; }
done
desc="Let any MCP AI app use your Android phone, on your terms"
mkdir -p "$out/Formula" "$out/bucket"

cat >"$out/Formula/latch.rb" <<RUBY
# SPDX-License-Identifier: AGPL-3.0-only
# Copyright (C) 2026 Aspersh Upadhyay and the Latch contributors
# Generated by packaging/render.sh for $tag; do not edit by hand.
class Latch < Formula
  desc "$desc"
  homepage "https://aspershupadhyay.github.io/latch/"
  version "$version"
  license "AGPL-3.0-only"

  on_macos do
    on_arm do
      url "$base/latch-$tag-macos-arm64.tar.gz"
      sha256 "$(sum "latch-$tag-macos-arm64.tar.gz")"
    end
    on_intel do
      url "$base/latch-$tag-macos-x86_64.tar.gz"
      sha256 "$(sum "latch-$tag-macos-x86_64.tar.gz")"
    end
  end

  on_linux do
    on_intel do
      url "$base/latch-$tag-linux-x86_64.tar.gz"
      sha256 "$(sum "latch-$tag-linux-x86_64.tar.gz")"
    end
  end

  livecheck do
    url :stable
    strategy :github_latest
  end

  def install
    bin.install "latch-gateway", "latch"
  end

  def caveats
    <<~EOS
      Start the gateway and show the QR code for the Latch app:
        latch start
      Keep it running in the background, also after a restart:
        latch autostart on
      After an upgrade, a background gateway picks up the new version with:
        latch restart
      Before brew uninstall, run latch uninstall (it turns background start off).
    EOS
  end

  test do
    assert_match "latch-gateway", shell_output("#{bin}/latch-gateway --version")
    assert_match "latch start", shell_output("#{bin}/latch help")
  end
end
RUBY

zip="latch-$tag-windows-x86_64.zip"
jq -n \
  --arg version "$version" \
  --arg desc "$desc" \
  --arg url "$base/$zip" \
  --arg hash "$(sum "$zip")" \
  '{
    version: $version,
    description: $desc,
    homepage: "https://aspershupadhyay.github.io/latch/",
    license: "AGPL-3.0-only",
    architecture: {"64bit": {url: $url, hash: $hash}},
    bin: ["latch.ps1", "latch-gateway.exe"],
    pre_uninstall: [
      "# Windows cannot replace or remove a program that is running.",
      "$p = Join-Path $env:USERPROFILE \".latch\\background.pid\"",
      "if (Test-Path $p) { Stop-Process -Id ([int](Get-Content $p)) -Force -ErrorAction SilentlyContinue }",
      "Get-Process latch-gateway -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue"
    ],
    post_install: [
      "# Background start was on: run the new version.",
      "if (Test-Path (Join-Path ([Environment]::GetFolderPath(\"Startup\")) \"Latch gateway.vbs\")) { & powershell.exe -NoProfile -ExecutionPolicy Bypass -File \"$dir\\latch.ps1\" autostart on | Out-Null }"
    ],
    notes: [
      "Start the gateway and show the QR code for the Latch app:  latch start",
      "Keep it running in the background, also after a restart:  latch autostart on",
      "When Windows asks, allow latch-gateway on private networks, so your phone can reach it.",
      "Before scoop uninstall latch, run latch uninstall (it turns background start off)."
    ],
    checkver: {github: "https://github.com/aspershupadhyay/latch"},
    autoupdate: {
      architecture: {"64bit": {url: "https://github.com/aspershupadhyay/latch/releases/download/v$version/latch-v$version-windows-x86_64.zip"}},
      hash: {url: "$baseurl/SHA256SUMS"}
    }
  }' >"$out/bucket/latch.json"

# winget: the gateway program only. winget puts .exe files on the PATH, not
# PowerShell scripts, so the `latch` command comes with Scoop or the one-line
# installer until it is part of latch-gateway.exe itself.
id=AspershUpadhyay.Latch
wdir="$out/winget/manifests/a/AspershUpadhyay/Latch/$version"
mkdir -p "$wdir"
cat >"$wdir/$id.yaml" <<YAML
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.version.1.6.0.schema.json
PackageIdentifier: $id
PackageVersion: $version
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.6.0
YAML
cat >"$wdir/$id.installer.yaml" <<YAML
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.installer.1.6.0.schema.json
PackageIdentifier: $id
PackageVersion: $version
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: latch-gateway.exe
    PortableCommandAlias: latch-gateway
Installers:
  - Architecture: x64
    InstallerUrl: $base/$zip
    InstallerSha256: $(sum "$zip" | tr a-f A-F)
ManifestType: installer
ManifestVersion: 1.6.0
YAML
cat >"$wdir/$id.locale.en-US.yaml" <<YAML
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.defaultLocale.1.6.0.schema.json
PackageIdentifier: $id
PackageVersion: $version
PackageLocale: en-US
Publisher: Aspersh Upadhyay
PublisherUrl: https://github.com/aspershupadhyay
PackageName: Latch
PackageUrl: https://aspershupadhyay.github.io/latch/
License: AGPL-3.0-only
LicenseUrl: https://github.com/aspershupadhyay/latch/blob/main/LICENSE
ShortDescription: $desc
Moniker: latch
Tags:
  - android
  - mcp
  - ai
ReleaseNotesUrl: https://github.com/aspershupadhyay/latch/releases/tag/$tag
ManifestType: defaultLocale
ManifestVersion: 1.6.0
YAML

echo "Wrote $out/Formula/latch.rb, $out/bucket/latch.json, and $wdir"
